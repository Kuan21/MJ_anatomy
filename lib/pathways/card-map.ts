/** 結構名稱 → 走向動畫目標；左側結構或沒有對應時回傳 null */
export function flowTargetFor(rawName:string|null|undefined):FlowTarget|null{
 if(!rawName)return null;
 if(/(^|[\s.])left\b|\.l(\.|$)/i.test(rawName))return null;
 const base=rawName
  .replace(/\.(?:r|l|j)(?=\.|$)/gi,'').replace(/\.\d+$/,'')
  .replace(/\b(?:right|left)\s+/gi,'').replace(/\bof (?:right|left) /gi,'of ')
  .replace(/[()]/g,'').replace(/\s+/g,' ').trim().toLowerCase();
 for(const [limb,mode,step,highlight,pattern] of ENTRIES)if(pattern.test(base))return {limb,mode,step,highlight};
 return null;
}
