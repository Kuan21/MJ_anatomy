// Where each special region (axillary fossa, quadrangular space, popliteal fossa …) is: the point where its boundary structures and contents come closest together, found from the real
// meshes, and the radius (app/mj-spaces.ts, `r`) of the sphere inside which the boundaries and contents are highlighted.
// A space is a gap between structures, so it has no mesh of its own: the centre minimises the largest distance to any of its boundary / content meshes that exist in the atlas.
// Run: node scripts/compute-space-ranges.mjs [--check]   → app/space-ranges.json, docs/space-ranges.md   (--check fails when either is out of date)
import fs from 'node:fs';
import {build} from 'esbuild';
import {fileURLToPath} from 'node:url';
import {loadFullAtlas} from './lib/full-atlas.mjs';
const root = new URL('../', import.meta.url), file = f => fileURLToPath(new URL(f, root));
const tmp = file('.sites-runtime/spaces-entry.mjs');
await build({entryPoints: [file('scripts/lib/spaces-entry.ts')], bundle: true, format: 'esm', platform: 'node', outfile: tmp, loader: {'.json': 'json'}, logLevel: 'error', external: ['three']});
const {SPACES, resolveSpace} = await import(tmp);
const {atlas, geometry} = loadFullAtlas();
const parts = atlas.parts, byId = new Map(parts.map(p => [p.id, p]));
const samples = new Map();
function points(id, cap = 500) {
  if (samples.has(id)) return samples.get(id);
  const g = geometry(byId.get(id)), v = g.positions, n = v.length / 3, step = Math.max(1, Math.floor(n / cap)), out = [];
  for (let i = 0; i < n; i += step) out.push(v[i * 3], v[i * 3 + 1], v[i * 3 + 2]);
  samples.set(id, out); return out;
}
const minDist2 = (c, pts) => { let best = Infinity; for (let i = 0; i < pts.length; i += 3) { const dx = pts[i] - c[0], dy = pts[i + 1] - c[1], dz = pts[i + 2] - c[2], d = dx * dx + dy * dy + dz * dz; if (d < best) best = d; } return best; };
const out = {}, rows = [];
for (const space of SPACES) {
  out[space.id] = {r: space.r};
  for (const side of ['left', 'right']) {
    const hit = resolveSpace(parts, space, side);
    const items = [...hit.boundaries, ...hit.contents].filter(h => h.ids.length).map(h => ({name: h.item.en, pts: h.ids.flatMap(id => points(id, 300))}));
    if (items.length < 2) { rows.push({id: space.id, side, items: items.length, c: null}); continue; }
    // candidates: the vertices of the content structures when there are any (they run through the space), otherwise of the boundaries
    const contentItems = hit.contents.filter(h => h.ids.length), candidates = (contentItems.length ? contentItems : hit.boundaries.filter(h => h.ids.length)).flatMap(h => h.ids.flatMap(id => points(id, 400)));
    let best = null;
    for (let i = 0; i < candidates.length; i += 3) {
      const c = [candidates[i], candidates[i + 1], candidates[i + 2]];
      let worst = 0; for (const it of items) { const d = minDist2(c, it.pts); if (d > worst) worst = d; if (best && worst >= best.cost) break; }
      if (!best || worst < best.cost) best = {c, cost: worst};
    }
    out[space.id][side] = {c: best.c.map(x => +x.toFixed(4)), reach: +Math.sqrt(best.cost).toFixed(4)};
    rows.push({id: space.id, side, items: items.length, c: out[space.id][side].c, reach: out[space.id][side].reach, r: space.r});
  }
}
const json = JSON.stringify(out, null, 1) + '\n';
const md = ['# Special regions: range spheres', '', 'Generated by `node scripts/compute-space-ranges.mjs`. 單位為公尺（模型座標）。中心＝各邊界與內容物網格最靠近的交會處；`reach` 是該點到最遠一條邊界／內容物的距離（愈小代表交會愈明確）；半徑 `r` 在 `app/mj-spaces.ts` 設定，邊界與內容物只在球內高亮並向邊緣淡出。', '',
  '| 區域 | 側 | 找到的結構數 | 中心 (x, y, z) | reach | 半徑 r |', '| --- | --- | --- | --- | --- | --- |',
  ...rows.map(r => `| ${r.id} | ${r.side} | ${r.items} | ${r.c ? r.c.join(', ') : '—（結構不足，無法定位）'} | ${r.reach ?? ''} | ${r.r ?? ''} |`), ''].join('\n');
if (process.argv.includes('--check')) {
  const ok = fs.existsSync(file('app/space-ranges.json')) && fs.readFileSync(file('app/space-ranges.json'), 'utf8') === json && fs.readFileSync(file('docs/space-ranges.md'), 'utf8') === md;
  if (!ok) { console.error('app/space-ranges.json or docs/space-ranges.md is out of date: run node scripts/compute-space-ranges.mjs'); process.exit(1); }
  console.log('space ranges up to date');
} else { fs.writeFileSync(file('app/space-ranges.json'), json); fs.writeFileSync(file('docs/space-ranges.md'), md); console.log(md); }
