// A part, head or belly of a muscle (transverse part of trapezius, long head of biceps …) must carry its own origin / insertion / action, not those of the whole muscle.
// Fails when such a part of the atlas falls back to the whole-muscle entry; writes the table of part facts for review to docs/muscle-part-facts.md.
// Run: node scripts/check-muscle-parts.mjs [--check]
import fs from 'node:fs';
import {build} from 'esbuild';
import {fileURLToPath} from 'node:url';
import {loadFullAtlas} from './lib/full-atlas.mjs';
const root = new URL('../', import.meta.url), file = f => fileURLToPath(new URL(f, root));
const tmp = file('.sites-runtime/muscle-facts-entry.mjs');
await build({entryPoints: [file('scripts/lib/muscle-facts-entry.ts')], bundle: true, format: 'esm', platform: 'node', outfile: tmp, logLevel: 'error'});
const {muscleFactsFor, MUSCLE_PART_FACTS} = await import(tmp);
const {atlas} = loadFullAtlas();
const partRe = /\b(part|head|belly|portion|bundle|fascicle|lamina|slip)s? of |^(superior|inferior|anterior|middle|posterior|upper|lower) (part|portion)/;
// parts that really share the facts of the whole muscle (listed on purpose)
const SHARED = /papillary muscle|cricothyroid|longus colli/;
const seen = new Map(), bad = [];
for (const p of atlas.parts) {
  if (p.system !== 'muscular') continue;
  const base = p.name.toLowerCase().replace(/\b(left|right)\b/g, '').replace(/\s+/g, ' ').trim();
  if (!partRe.test(base) || SHARED.test(base) || seen.has(base)) continue;
  const f = muscleFactsFor(p.name); seen.set(base, f);
  if (!f || !MUSCLE_PART_FACTS[base]) bad.push(base);
}
const rows = [...seen.entries()].sort((a, b) => a[0].localeCompare(b[0])).map(([k, f]) => `| ${k} | ${f?.chinese ?? '—'} | ${f?.originEn ?? ''} | ${f?.insertionEn ?? ''} | ${f?.actionEn ?? ''} |`);
const md = ['# Muscle parts: origin, insertion and action', '', 'Generated by `node scripts/check-muscle-parts.mjs`. Each part, head or belly of a muscle has its own facts (`app/mj-muscle-facts-parts.ts`); the whole-muscle entries are not copied onto them.', '', '| Part | 中文 | Origin | Insertion | Action |', '| --- | --- | --- | --- | --- |', ...rows, ''].join('\n');
if (process.argv.includes('--check')) {
  if (bad.length) { console.error('parts without their own muscle facts:\n  ' + bad.join('\n  ')); process.exit(1); }
  if (!fs.existsSync(file('docs/muscle-part-facts.md')) || fs.readFileSync(file('docs/muscle-part-facts.md'), 'utf8') !== md) { console.error('docs/muscle-part-facts.md is out of date: run node scripts/check-muscle-parts.mjs'); process.exit(1); }
  console.log(`muscle parts: ${seen.size} parts, all with their own facts`);
} else { fs.writeFileSync(file('docs/muscle-part-facts.md'), md); console.log(`${seen.size} parts, ${bad.length} without their own facts`); if (bad.length) console.log(bad.join('\n')); }
